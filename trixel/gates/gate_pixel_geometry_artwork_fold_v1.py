#!/usr/bin/env python3
"""Pixel art fold-vs-stretch proof: does the ART fold, or does it stretch?

trial 2.5 (gate_pixel_geometry_hinge_fold_v1.py, frozen, NOT modified here)
already proved that trixel.pixel_geometry can hard-fold a discrete
CellFootprint 90 degrees without changing cell identity, adjacency, or the
declared 1.0 cell metric. That was a geometry-only proof.

This gate attaches real, deterministic pixel artwork
(fixtures/pixel_geometry/pixel_fold_diagnostic_16x16.png, generated by
tools/generate_pixel_geometry_diagnostic_art.py) to a 16x16 footprint and
compares three specimens built from the SAME artwork bytes and the SAME
intrinsic corner addresses:

  A -- FLAT              (embed_flat, the control)
  B -- HARD FOLD          (embed_hard_90_degree_hinge_fold, hinge at x=8,
                            i.e. exactly between diagnostic-art columns
                            0..7 and 8..15 -- frozen production embedding)
  C -- FORCED DIAGONAL STRETCH (a LOCAL, non-production toxic position map
                            built only in this gate -- never added to
                            embedding_v1.py -- that fixes a source cell
                            edge's world-space endpoints run=1.0/rise=1.0
                            apart, i.e. geometric length sqrt(2), while its
                            UV interval stays the nominal one-pixel span)

The law under test (artwork_mapping_v1.py's whole reason to exist):

    THE EMBEDDING MUST NEVER ALTER THE UV ADDRESS.

A green result here means BOTH of:
  - the hard fold preserved the artwork metric (no deformation detected)
  - the toxic diagonal control WAS correctly detected as deformation

Not just the first one. A gate that only checked the fold would not have
proven anything the frozen hinge gate hadn't already proven; the toxic
control is what proves this gate's detector has teeth.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
TOOLS_DIR = REPO_ROOT / "tools"
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

from PIL import Image

from trixel.pixel_geometry.addressing_v1 import build_footprint, cell_addresses, corner_index
from trixel.pixel_geometry.adjacency_v1 import compiled_adjacency_matches_source
from trixel.pixel_geometry.artwork_mapping_v1 import footprint_corner_uvs, uvs_are_identical
from trixel.pixel_geometry.compiler_v1 import compile_footprint, edge_lengths
from trixel.pixel_geometry.contracts_v1 import (
    EMBEDDING_FLAT,
    EMBEDDING_HARD_90_DEGREE_HINGE_FOLD,
)
from trixel.pixel_geometry.embedding_v1 import embed_flat, embed_hard_90_degree_hinge_fold

import generate_pixel_geometry_diagnostic_art as diagnostic_art

ART_PATH = REPO_ROOT / "fixtures" / "pixel_geometry" / "pixel_fold_diagnostic_16x16.png"
SIZE = 16
HINGE_X = 8  # exactly between diagnostic-art columns 0..7 and 8..15

CHECKS: list[bool] = []


def report(name: str, ok: bool, message: str = "") -> bool:
    suffix = f" — {message}" if message else ""
    print(f"[PIXEL_GEOMETRY_ARTWORK_FOLD][{name}] {'TRUE' if ok else 'FALSE'}{suffix}")
    CHECKS.append(ok)
    return ok


def close(a: float, b: float, tol: float = 1e-9) -> bool:
    return abs(a - b) <= tol


def edges_with_addresses(compiled: dict) -> list[tuple[tuple[int, int], tuple[int, int], float]]:
    """Every cell-grid edge as (address_a, address_b, geometric_length) --
    like compiler_v1.edge_lengths() but keeping the addresses attached, so
    a deformation can be reported against the specific corners involved
    instead of only an aggregate min/max."""
    width, height = compiled["footprint_width"], compiled["footprint_height"]
    positions = compiled["positions"]

    def dist(a: int, b: int) -> float:
        ax, ay, az = positions[a]
        bx, by, bz = positions[b]
        return ((ax - bx) ** 2 + (ay - by) ** 2 + (az - bz) ** 2) ** 0.5

    edges = []
    for r in range(height + 1):
        for x in range(width):
            a, b = (x, r), (x + 1, r)
            edges.append((a, b, dist(corner_index(*a, width), corner_index(*b, width))))
    for x in range(width + 1):
        for r in range(height):
            a, b = (x, r), (x, r + 1)
            edges.append((a, b, dist(corner_index(*a, width), corner_index(*b, width))))
    return edges


def artwork_deformation_report(
    compiled: dict, uv_map: dict[tuple[int, int], tuple[float, float]], *, tol: float = 1e-9
) -> list[dict]:
    """The actual detector: for every cell-grid edge, the DECLARED intrinsic
    length is always 1.0 cell and its UV interval is always the nominal
    one-pixel span computed purely from address (uv_map never varies with
    geometry). An edge is flagged as artwork deformation exactly when its
    realized GEOMETRIC length diverges from that declared 1.0 while its UV
    interval stayed the nominal, unchanged span -- i.e. the same one-pixel
    stretch of artwork is being asked to cover a different-length edge.
    """
    flagged = []
    for a, b, geometric_length in edges_with_addresses(compiled):
        ua, va = uv_map[a]
        ub, vb = uv_map[b]
        uv_span = ((ua - ub) ** 2 + (va - vb) ** 2) ** 0.5
        deformed = not close(geometric_length, 1.0, tol)
        if deformed:
            flagged.append(
                {
                    "edge": (a, b),
                    "geometric_length": geometric_length,
                    "uv_span": uv_span,
                    "stretch_factor": geometric_length / 1.0,
                }
            )
    return flagged


def build_footprint_from_art(image: Image.Image) -> dict:
    payload = [[image.getpixel((x, row)) for x in range(SIZE)] for row in range(SIZE)]
    return build_footprint(SIZE, SIZE, payload)


def main() -> int:
    # --- DIAGNOSTIC ART CHECKS -------------------------------------------
    if not ART_PATH.exists():
        report("DIAGNOSTIC_ART_IS_16X16", False, f"missing {ART_PATH} -- run tools/generate_pixel_geometry_diagnostic_art.py first")
        report("DIAGNOSTIC_ART_HAS_NO_RESAMPLING", False, "skipped, art file missing")
        print("[PIXEL_GEOMETRY_ARTWORK_FOLD][ALL_GATES] false")
        return 1

    art_image = Image.open(ART_PATH).convert("RGB")
    report("DIAGNOSTIC_ART_IS_16X16", art_image.size == (SIZE, SIZE), f"got {art_image.size}")

    # No resampling anywhere between generation and disk: regenerate the
    # image in-memory from the same deterministic rules and compare it
    # pixel-for-pixel against what is actually on disk.
    regenerated = diagnostic_art.build_diagnostic_image()
    pixels_match = all(
        art_image.getpixel((x, y)) == regenerated.getpixel((x, y))
        for y in range(SIZE)
        for x in range(SIZE)
    )
    report("DIAGNOSTIC_ART_HAS_NO_RESAMPLING", pixels_match, "on-disk PNG must equal the deterministic in-memory generation, pixel for pixel")

    footprint = build_footprint_from_art(art_image)

    # --- A: FLAT (control) ------------------------------------------------
    flat_positions = embed_flat(footprint)
    flat_compiled = compile_footprint(footprint, flat_positions, embedding_id=EMBEDDING_FLAT)
    flat_uv = footprint_corner_uvs(footprint)

    # --- B: HARD FOLD -------------------------------------------------------
    fold_positions = embed_hard_90_degree_hinge_fold(footprint, hinge_corner_x=HINGE_X)
    fold_compiled = compile_footprint(footprint, fold_positions, embedding_id=EMBEDDING_HARD_90_DEGREE_HINGE_FOLD)
    fold_uv = footprint_corner_uvs(footprint)  # same footprint, same function -- UV never derives from position

    report("FLAT_AND_FOLD_USE_IDENTICAL_INTRINSIC_UVS", uvs_are_identical(flat_uv, fold_uv))

    fold_edges = edge_lengths(fold_compiled)
    report(
        "HARD_FOLD_ALL_CELL_EDGES_REMAIN_1_0",
        all(close(length, 1.0) for length in fold_edges),
        f"min={min(fold_edges):.6f} max={max(fold_edges):.6f} n={len(fold_edges)}",
    )
    report("HARD_FOLD_ARTWORK_COORDINATES_UNCHANGED", uvs_are_identical(flat_uv, fold_uv))
    report(
        "HARD_FOLD_SOURCE_ADJACENCY_UNCHANGED",
        compiled_adjacency_matches_source(footprint, fold_compiled["compiled_adjacency"]),
    )
    report(
        "HARD_FOLD_ALL_CELLS_PRESERVED_1_TO_1",
        len(fold_compiled["dispositions"]) == SIZE * SIZE
        and all(v == "PRESERVED_1_TO_1" for v in fold_compiled["dispositions"].values()),
    )

    # --- C: FORCED DIAGONAL STRETCH (toxic, local to this gate only) -----
    # NOT a production embedding: shear every corner's Y by its own X, so a
    # source cell edge with declared intrinsic length 1.0 gets world-space
    # endpoints separated by run=1.0, rise=1.0 -> geometric length sqrt(2).
    # UV stays whatever footprint_corner_uvs() says for that same address,
    # since UV is never derived from position.
    diagonal_positions = {(x, r): (float(x), float(x), float(r)) for x, r in flat_positions}
    diagonal_compiled = compile_footprint(footprint, diagonal_positions, embedding_id="toxic_forced_diagonal_stretch")
    diagonal_uv = footprint_corner_uvs(footprint)

    diagonal_edges = edge_lengths(diagonal_compiled)
    expected_stretch_factor = math.sqrt(2.0)
    stretched_lengths = [length for length in diagonal_edges if not close(length, 1.0)]
    measured_stretch_factor = max(stretched_lengths) if stretched_lengths else float("nan")

    report(
        "TOXIC_DIAGONAL_HAS_EDGE_GREATER_THAN_1_0",
        any(length > 1.0 + 1e-9 for length in diagonal_edges),
        f"max={max(diagonal_edges):.9f}",
    )
    report(
        "TOXIC_DIAGONAL_EXPECTED_STRETCH_FACTOR_DETECTED",
        bool(stretched_lengths) and close(measured_stretch_factor, expected_stretch_factor, tol=1e-6),
        f"measured={measured_stretch_factor:.9f} expected={expected_stretch_factor:.9f}",
    )
    report("TOXIC_DIAGONAL_UV_SPAN_REMAINS_UNCHANGED", uvs_are_identical(flat_uv, diagonal_uv))

    # --- Composite verdicts: the deformation detector itself -------------
    fold_deformations = artwork_deformation_report(fold_compiled, fold_uv)
    diagonal_deformations = artwork_deformation_report(diagonal_compiled, diagonal_uv)

    report(
        "FOLD_IS_EMBEDDING_NOT_ARTWORK_DEFORMATION",
        len(fold_deformations) == 0,
        f"flagged={len(fold_deformations)}" if fold_deformations else "",
    )
    diagonal_uv_spans_nominal = all(
        close(d["uv_span"], 1.0 / SIZE) or close(d["uv_span"], 0.0) for d in diagonal_deformations
    )
    report(
        "DIAGONAL_CONTROL_IS_DETECTED_AS_ARTWORK_DEFORMATION",
        len(diagonal_deformations) > 0 and diagonal_uv_spans_nominal,
        f"flagged={len(diagonal_deformations)}, max_stretch_factor="
        f"{max((d['stretch_factor'] for d in diagonal_deformations), default=float('nan')):.9f}",
    )

    all_ok = all(CHECKS)
    print(f"[PIXEL_GEOMETRY_ARTWORK_FOLD][ALL_GATES] {'true' if all_ok else 'false'}")
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
